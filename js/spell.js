/* 문자열 하나에서 틀린 곳을 찾아 [{s,e,t,fix,note}] 로 돌려줘요 */
function spellFind(str){
  const out=[];
  for(const R of SP_RULES){
    R.re.lastIndex=0;let m;
    while(m=R.re.exec(str)){
      if(!m[0]){R.re.lastIndex++;continue}
      if(R.ok&&!R.ok(m,str))continue;
      const e=m.index+m[0].length,full=str.slice(m.index).replace(R.one,R.r); /* 뒤따르는 조건(?=…)까지 포함해 치환한 뒤, 찾은 부분만 잘라 써요 */
      out.push({s:m.index,e,t:m[0],fix:full.slice(0,full.length-(str.length-e)),note:R.n});
    }
  }
  /* 겹치면 앞선 것만 남겨요 */
  out.sort((a,b)=>a.s-b.s||b.e-a.e);
  const res=[];
  for(const x of out)if(!res.length||x.s>=res[res.length-1].e)res.push(x);
  return res;
}
/* 화 전체(줄바꿈 포함)에서 찾아요. i 는 줄 번호, x 는 목록에 보일 앞뒤 문맥 */
function spellText(t){
  const r=[];
  t.split('\n').forEach((ln,i)=>{if(ln)for(const m of spellFind(ln))r.push({...m,i,x:(m.s>12?'…':'')+ln.slice(Math.max(0,m.s-12),m.e+12)+(ln.length>m.e+12?'…':'')})});
  return r;
}
